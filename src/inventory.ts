import type { Analysis } from './analyze.js';
import { DATA_TYPES } from './types.js';
import type { DataType, PlayPurpose, Purpose, ScanResult } from './types.js';
import { ASC_TYPES } from './appstore.js';

/** Apple's and Google's purposes, in one set of plain words. */
const PLAIN: Record<Purpose | PlayPurpose, string> = {
  'app-functionality': 'App features',
  analytics: 'Analytics',
  'third-party-advertising': 'Advertising and marketing',
  'developer-advertising': 'Advertising and marketing',
  advertising: 'Advertising and marketing',
  'product-personalization': 'Personalization',
  personalization: 'Personalization',
  'fraud-prevention': 'Fraud prevention and security',
  'developer-communications': 'Messages to users',
  'account-management': 'Account management',
  other: 'Other',
};
const PLAIN_ORDER = [...new Set(Object.values(PLAIN))];

/**
 * `report --format inventory`: what the app collects, who receives it and why, in plain words,
 * for the person who writes the privacy policy. Facts from the scan only, no legal wording.
 */
interface Row {
  type: DataType;
  purposes: Set<string>;
  services: Set<string>;
  ios: boolean;
  android: boolean;
  linked: boolean;
  tracking: boolean;
  shared: boolean;
  conditions: string[];
}

export function formatInventory(scan: ScanResult, a: Analysis): string {
  // Show services by name ("Firebase Analytics"), not package ("@react-native-firebase/analytics").
  const service = (pkg: string) => scan.packages.find((p) => p.name === pkg)?.rule?.name ?? pkg;
  const rows = new Map<DataType, Row>();
  const row = (type: DataType) => {
    let r = rows.get(type);
    if (!r) rows.set(type, (r = { type, purposes: new Set(), services: new Set(), ios: false, android: false, linked: false, tracking: false, shared: false, conditions: [] }));
    return r;
  };
  const addPurpose = (r: Row, p: Purpose | PlayPurpose) => r.purposes.add(PLAIN[p]);

  for (const d of a.data) {
    const r = row(d.type);
    r.ios = true;
    r.linked ||= d.linked || d.conditional.some((x) => x.item.linked);
    r.tracking ||= d.tracking || d.conditional.some((x) => x.item.tracking);
    for (const p of [...d.purposes, ...d.conditional.flatMap((x) => x.item.purposes)]) addPurpose(r, p);
    for (const pkg of d.packages) r.services.add(service(pkg));
    for (const x of d.conditional) {
      r.services.add(service(x.pkg));
      r.conditions.push(`${service(x.pkg)}: ${x.condition}`);
    }
  }
  for (const d of a.play) {
    const r = row(d.type);
    r.android = true;
    r.shared ||= d.shared || d.conditional.some((x) => x.item.shared);
    for (const p of [...d.purposes, ...d.conditional.flatMap((x) => x.item.purposes)]) addPurpose(r, p);
    for (const pkg of d.packages) r.services.add(service(pkg));
    for (const x of d.conditional) {
      r.services.add(service(x.pkg));
      const c = `${service(x.pkg)}: ${x.condition}`;
      if (!r.conditions.includes(c)) r.conditions.push(c);
    }
  }

  const date = new Date().toLocaleDateString('en-CA');
  const out: string[] = [];
  out.push('# Data inventory', '');
  out.push(`Generated by rn-privacy on ${date}. A plain list of the data this app collects, who receives it and why, for whoever writes`);
  out.push('the privacy policy. It is built from the app\'s dependencies and the rules in rn-privacy.config.json. It is not legal text,');
  out.push('and it does not know what your own servers do with the data.', '');

  out.push('## Data collected', '');
  const order = Object.keys(ASC_TYPES);
  const list = [...rows.values()].sort((x, y) => order.indexOf(x.type) - order.indexOf(y.type));
  if (!list.length) out.push('No data collection found in known libraries or your rules.', '');
  else {
    out.push('| Data | Why | Collected by | Platforms | Linked to the user | Used for tracking (iOS) | Shared (Google Play) |', '| --- | --- | --- | --- | --- | --- | --- |');
    for (const r of list) {
      const platforms = [r.ios && 'iOS', r.android && 'Android'].filter(Boolean).join(', ');
      out.push(`| ${DATA_TYPES[r.type].label} | ${PLAIN_ORDER.filter((p) => r.purposes.has(p)).join(', ') || 'Not stated'} | ${[...r.services].join(', ')} | ${platforms} | ${r.ios ? (r.linked ? 'Yes' : 'No') : '-'} | ${r.ios ? (r.tracking ? 'Yes' : 'No') : '-'} | ${r.android ? (r.shared ? 'Yes' : 'No') : '-'} |`);
    }
    out.push('');
    const conditional = list.filter((r) => r.conditions.length);
    if (conditional.length) {
      out.push('Only in some setups:', '');
      for (const r of conditional) out.push(`- **${DATA_TYPES[r.type].label}**: ${r.conditions.join('; ')}`);
      out.push('');
    }
  }

  // Third parties: every service with a rule or a manifest that says it collects something.
  const services = new Map<string, { packages: Set<string>; data: Set<string>; urls: Set<string>; own: boolean; app: boolean }>();
  for (const r of list) {
    for (const s of r.services) {
      let e = services.get(s);
      if (!e) services.set(s, (e = { packages: new Set(), data: new Set(), urls: new Set(), own: false, app: true }));
      e.data.add(DATA_TYPES[r.type].label);
    }
  }
  for (const p of scan.packages) {
    const e = services.get(service(p.name));
    if (!e) continue;
    e.packages.add(p.name);
    if (p.rule?.origin) e.own = true;
    // A rule without packages describes the app itself, not a third party.
    if (p.rule?.packages.length !== 0) e.app = false;
    for (const u of [...(p.rule?.sources ?? []), ...(p.rule?.android?.sources ?? [])]) e.urls.add(u);
  }
  const thirdParty = [...services].filter(([, e]) => !e.app);
  if (thirdParty.length) {
    out.push('## Services that receive data', '');
    out.push('| Service | Package | Data | More information |', '| --- | --- | --- | --- |');
    for (const [name, e] of thirdParty.sort(([x], [y]) => x.localeCompare(y))) {
      out.push(`| ${name} | ${[...e.packages].map((p) => `\`${p}\``).join(', ')} | ${[...e.data].join(', ')} | ${[...e.urls].join('<br>') || (e.own ? 'Your rule in rn-privacy.config.json' : '')} |`);
    }
    out.push('');
  }
  const ownData = [...services].filter(([, e]) => e.app);
  if (ownData.length) {
    out.push('## Collected by your own app', '', 'From the rules without packages in rn-privacy.config.json:', '');
    for (const [name, e] of ownData) out.push(`- **${name}**: ${[...e.data].join(', ')}`);
    out.push('');
  }

  if (a.tracking.length) {
    out.push('## Tracking domains', '', 'Domains the SDKs declare for tracking (used only if the user allows tracking on iOS):', '');
    for (const t of a.tracking) if (t.domains.length) out.push(`- ${service(t.pkg)}: ${t.domains.join(', ')}`);
    out.push('');
  }

  if (a.access.length || a.android.length) {
    out.push('## Device data the app can access', '', 'Through these permissions the app can read data on the device. It only needs to be in the policy if it leaves the device.', '');
    for (const acc of a.access) out.push(`- ${DATA_TYPES[acc.type].label} (iOS and Android): ${acc.packages.join(', ')}`);
    for (const p of a.android) if (!a.access.some((x) => x.type === p.type)) out.push(`- ${p.label} (Android permission \`${p.permission.split('.').pop()}\`): ${p.sources.join(', ')}`);
    out.push('');
  }

  out.push('## Not covered', '');
  out.push('- What your own servers store, for how long, and who can see it.');
  out.push('- Data you send to an SDK yourself (for example user properties or event names) beyond what is listed above.');
  out.push('- Libraries without a rule: they are scanned for Apple\'s required reason APIs, but what they collect is not known. Describe them in rn-privacy.config.json.');
  return out.join('\n') + '\n';
}
